package network

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/david/speakerctld/internal/storage"
)

// RuntimeDir is the directory for runtime files (tmpfs).
const RuntimeDir = "/run/speakerctld"

// SpeakerctldConnectionPrefix is the prefix used for NetworkManager connection names
const SpeakerctldConnectionPrefix = "Speakerctld-"

// State represents the speaker state (defined locally to avoid import cycle with state package)
type State string

// State constants (must match those in internal/state package)
const (
	FirstBootAP State = "FIRSTBOOT_AP"
	WifiConnect State = "WIFI_CONNECT"
	Online      State = "ONLINE"
	FallbackAP  State = "FALLBACK_AP"
)

// ConfigGenerator generates network configuration files for AP and client modes.
// For WiFi client mode, it uses NetworkManager via DBus instead of wpa_supplicant.
type ConfigGenerator struct {
	storage      storage.Storage
	runtimeDir  string
	nmManager   *WifiConnectionManager
	useNM       bool
}

// ConfigGeneratorOption is a functional option for ConfigGenerator
// This allows for flexible configuration without changing the constructor signature
type ConfigGeneratorOption func(*ConfigGenerator)

// WithNetworkManager enables NetworkManager integration
func WithNetworkManager() ConfigGeneratorOption {
	return func(cg *ConfigGenerator) {
		cg.useNM = true
	}
}

// WithNetworkManagerClient sets a custom NetworkManager client
func WithNetworkManagerClient(client *WifiConnectionManager) ConfigGeneratorOption {
	return func(cg *ConfigGenerator) {
		cg.nmManager = client
		cg.useNM = true
	}
}

// NewConfigGenerator creates a new ConfigGenerator.
// By default, it uses NetworkManager for WiFi client management.
// Pass options to customize behavior (e.g., WithNetworkManager() to explicitly enable NM).
func NewConfigGenerator(st storage.Storage, opts ...ConfigGeneratorOption) *ConfigGenerator {
	cg := &ConfigGenerator{
		storage:     st,
		runtimeDir: RuntimeDir,
		useNM:      true, // Use NetworkManager by default
	}

	for _, opt := range opts {
		opt(cg)
	}

	// Initialize NetworkManager client if needed
	if cg.useNM && cg.nmManager == nil {
		client, err := NewWifiConnectionManager()
		if err != nil {
			// Log error but continue - fallback to file-based config if needed
			// In production, you might want to handle this more gracefully
			cg.useNM = false
		} else {
			cg.nmManager = client
		}
	}

	return cg
}

// GenerateHostapdConfig generates the hostapd configuration for AP mode.
// It creates different configurations based on the current state:
// - FIRSTBOOT_AP: Open AP with Speakerctld-Setup-XXXX SSID
// - FALLBACK_AP: Secured AP with Speakerctld-Recovery-XXXX SSID
func (g *ConfigGenerator) GenerateHostapdConfig(currentState State, deviceID string) error {
	// Ensure runtime directory exists
	if err := os.MkdirAll(g.runtimeDir, 0755); err != nil {
		return fmt.Errorf("failed to create runtime directory: %w", err)
	}

	configPath := filepath.Join(g.runtimeDir, "hostapd.conf")

	var config string
	switch currentState {
	case FirstBootAP:
		// Open AP for first boot
		config = g.generateOpenAPConfig(deviceID)
	case FallbackAP:
		// Secured AP for fallback
		config = g.generateSecuredAPConfig(deviceID)
	default:
		// Don't generate hostapd config for non-AP states
		// Remove existing config if it exists
		if err := os.Remove(configPath); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove hostapd config: %w", err)
		}
		return nil
	}

	// Write atomically
	tmpPath := configPath + ".tmp"
	if err := os.WriteFile(tmpPath, []byte(config), 0644); err != nil {
		return fmt.Errorf("failed to write hostapd config: %w", err)
	}

	// Sync and rename
	if err := syncAndRename(tmpPath, configPath); err != nil {
		return err
	}

	return nil
}

// generateOpenAPConfig generates configuration for an open AP.
func (g *ConfigGenerator) generateOpenAPConfig(deviceID string) string {
	ssid := fmt.Sprintf("Speakerctld-Setup-%s", deviceID)
	
	return fmt.Sprintf(`# Hostapd configuration for Speakerctld First Boot AP
# Generated by speakerctld

interface=wlan0
driver=nl80211
ssid=%s
hw_mode=g
channel=6
wmm_enabled=0
macaddr_acl=0
auth_algs=1
ignore_broadcast_ssid=0
wpa=0
`, ssid)
}

// generateSecuredAPConfig generates configuration for a secured AP.
func (g *ConfigGenerator) generateSecuredAPConfig(deviceID string) string {
	// Load recovery password from device storage
	deviceInfo, err := g.storage.(*storage.FileStorage).LoadDeviceInfo()
	var password string
	if err == nil && deviceInfo != nil {
		password = deviceInfo.RecoveryPassword
	}
	if password == "" {
		password = "speakerctld-recovery"
	}
	
	ssid := fmt.Sprintf("Speakerctld-Recovery-%s", deviceID)
	
	return fmt.Sprintf(`# Hostapd configuration for Speakerctld Fallback AP
# Generated by speakerctld

interface=wlan0
driver=nl80211
ssid=%s
hw_mode=g
channel=11
wmm_enabled=0
macaddr_acl=0
auth_algs=1
wpa=2
wpa_passphrase=%s
wpa_key_mgmt=WPA-PSK
wpa_pairwise=TKIP
rsn_pairwise=CCMP
`, ssid, password)
}

// GenerateWpaSupplicantConfig is deprecated. Use ConfigureWifiClient instead.
// This method is kept for backward compatibility but does nothing.
func (g *ConfigGenerator) GenerateWpaSupplicantConfig() error {
	// If NetworkManager is available, use it instead
	if g.useNM && g.nmManager != nil {
		return g.ConfigureWifiClient()
	}
	
	// Fallback to old behavior if NM is not available
	// Load Wi-Fi configuration
	wifiConfig, err := g.storage.LoadWifiConfig()
	if err != nil {
		return fmt.Errorf("failed to load wifi config: %w", err)
	}
	if wifiConfig == nil {
		// No configuration, remove existing file
		configPath := filepath.Join(g.runtimeDir, "wpa_supplicant.conf")
		if err := os.Remove(configPath); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove wpa_supplicant config: %w", err)
		}
		return nil
	}

	// Ensure runtime directory exists
	if err := os.MkdirAll(g.runtimeDir, 0755); err != nil {
		return fmt.Errorf("failed to create runtime directory: %w", err)
	}

	configPath := filepath.Join(g.runtimeDir, "wpa_supplicant.conf")

	config := g.generateClientConfig(wifiConfig)

	// Write atomically
	tmpPath := configPath + ".tmp"
	if err := os.WriteFile(tmpPath, []byte(config), 0644); err != nil {
		return fmt.Errorf("failed to write wpa_supplicant config: %w", err)
	}

	// Sync and rename
	if err := syncAndRename(tmpPath, configPath); err != nil {
		return err
	}

	return nil
}

// ConfigureWifiClient configures WiFi client connection using NetworkManager.
// This replaces the old wpa_supplicant-based configuration.
// It loads the WiFi configuration from storage and creates/activates a NetworkManager connection.
func (g *ConfigGenerator) ConfigureWifiClient() error {
	if !g.useNM || g.nmManager == nil {
		return fmt.Errorf("NetworkManager is not enabled or available")
	}

	// Load Wi-Fi configuration
	wifiConfig, err := g.storage.LoadWifiConfig()
	if err != nil {
		return fmt.Errorf("failed to load wifi config: %w", err)
	}

	if wifiConfig == nil {
		// No configuration, clean up any existing Speakerctld connections
		if err := g.nmManager.Cleanup(); err != nil {
			// Non-critical error, continue
			// In production, you might want to log this
		}
		return nil
	}

	// Connect using NetworkManager
	if err := g.nmManager.Connect(wifiConfig.SSID, wifiConfig.PSK); err != nil {
		return fmt.Errorf("failed to configure WiFi client: %w", err)
	}

	return nil
}

// generateClientConfig generates wpa_supplicant configuration for a client.
func (g *ConfigGenerator) generateClientConfig(config *storage.WifiConfig) string {
	// Simple configuration for WPA2-PSK
	if config.PSK != "" {
		return fmt.Sprintf(`ctrl_interface=DIR=/run/wpa_supplicant GROUP=netdev
update_config=1
country=FR

network={
    ssid="%s"
    psk="%s"
    key_mgmt=WPA-PSK
}`, config.SSID, config.PSK)
	}
	// Open network
	return fmt.Sprintf(`ctrl_interface=DIR=/run/wpa_supplicant GROUP=netdev
update_config=1
country=FR

network={
    ssid="%s"
    key_mgmt=NONE
}`, config.SSID)
}

// Cleanup removes all generated runtime configuration files and NetworkManager connections.
func (g *ConfigGenerator) Cleanup() error {
	// Clean up runtime files
	configs := []string{
		"hostapd.conf",
		"wpa_supplicant.conf",
	}

	for _, config := range configs {
		configPath := filepath.Join(g.runtimeDir, config)
		if err := os.Remove(configPath); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove %s: %w", configPath, err)
		}
	}

	// Clean up NetworkManager connections if enabled
	if g.useNM && g.nmManager != nil {
		if err := g.nmManager.Cleanup(); err != nil {
			// Non-critical error, but we should try to close the connection
			// In production, you might want to log this
			g.nmManager.Close()
			return fmt.Errorf("failed to clean up NetworkManager connections: %w", err)
		}
		g.nmManager.Close()
		g.nmManager = nil
	}

	return nil
}

// syncAndRename performs an atomic file write by syncing and renaming.
func syncAndRename(tmpPath, finalPath string) error {
	// Open and sync the temp file
	f, err := os.Open(tmpPath)
	if err != nil {
		os.Remove(tmpPath)
		return fmt.Errorf("failed to open temp file: %w", err)
	}
	if err := f.Sync(); err != nil {
		f.Close()
		os.Remove(tmpPath)
		return fmt.Errorf("failed to sync temp file: %w", err)
	}
	f.Close()

	// Atomic rename
	if err := os.Rename(tmpPath, finalPath); err != nil {
		os.Remove(tmpPath)
		return fmt.Errorf("failed to rename file: %w", err)
	}

	return nil
}
